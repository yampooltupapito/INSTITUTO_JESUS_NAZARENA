-- Eliminar tablas en orden inverso a sus dependencias si existen
DROP TABLE IF EXISTS auditoria_evento CASCADE;
DROP TABLE IF EXISTS notificacion CASCADE;
DROP TABLE IF EXISTS alerta_asistencia CASCADE;
DROP TABLE IF EXISTS configuracion_alerta_asistencia CASCADE;
DROP TABLE IF EXISTS calendario_escolar CASCADE;
DROP TABLE IF EXISTS horario_asistencia CASCADE;
DROP TABLE IF EXISTS estudiante_apoderado CASCADE;
DROP TABLE IF EXISTS justificacion CASCADE;
DROP TABLE IF EXISTS asistencia CASCADE;
DROP TABLE IF EXISTS matricula CASCADE;
DROP TABLE IF EXISTS seccion CASCADE;
DROP TABLE IF EXISTS grado CASCADE;
DROP TABLE IF EXISTS anio_escolar CASCADE;
DROP TABLE IF EXISTS usuario CASCADE;
DROP TABLE IF EXISTS rol_permiso CASCADE;
DROP TABLE IF EXISTS permiso CASCADE;
DROP TABLE IF EXISTS rol CASCADE;
DROP TABLE IF EXISTS persona_actor CASCADE;
DROP TABLE IF EXISTS tipo_actor CASCADE;
DROP TABLE IF EXISTS persona CASCADE;

-- 1. TABLA: persona
CREATE TABLE persona (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento VARCHAR(20) NOT NULL DEFAULT 'DNI',
    numero_documento VARCHAR(20) NOT NULL UNIQUE,
    nombres VARCHAR(100) NOT NULL,
    apellido_paterno VARCHAR(100) NOT NULL,
    apellido_materno VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    sexo VARCHAR(10) NOT NULL,
    telefono VARCHAR(20),
    correo VARCHAR(100),
    direccion VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50)
);

-- 2. TABLA: tipo_actor
CREATE TABLE tipo_actor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50)
);

-- 3. TABLA: persona_actor
CREATE TABLE persona_actor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    persona_id BIGINT NOT NULL REFERENCES persona(id),
    tipo_actor_id BIGINT NOT NULL REFERENCES tipo_actor(id),
    fecha_inicio DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_fin DATE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50),
    CONSTRAINT uk_persona_tipo_actor UNIQUE (persona_id, tipo_actor_id)
);

-- 4. TABLA: rol
CREATE TABLE rol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50)
);

-- 5. TABLA: permiso
CREATE TABLE permiso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    modulo VARCHAR(50) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50)
);

-- 6. TABLA: rol_permiso (Tabla de unión con Clave Primaria compuesta)
CREATE TABLE rol_permiso (
    rol_id BIGINT NOT NULL REFERENCES rol(id),
    permiso_id BIGINT NOT NULL REFERENCES permiso(id),
    PRIMARY KEY (rol_id, permiso_id)
);

-- 7. TABLA: usuario
CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    persona_id BIGINT NOT NULL REFERENCES persona(id),
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    rol_id BIGINT NOT NULL REFERENCES rol(id),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    ultimo_acceso TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50)
);

-- 8. TABLA: anio_escolar
CREATE TABLE anio_escolar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio INT NOT NULL UNIQUE,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50),
    CONSTRAINT chk_anio_escolar_fechas CHECK (fecha_fin >= fecha_inicio)
);

-- 9. TABLA: grado
CREATE TABLE grado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nivel VARCHAR(20) NOT NULL,
    numero INT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50),
    CONSTRAINT chk_grado_nivel CHECK (nivel IN ('INICIAL', 'PRIMARIA', 'SECUNDARIA')),
    CONSTRAINT uk_grado_nivel_numero UNIQUE (nivel, numero)
);

-- 10. TABLA: seccion
CREATE TABLE seccion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grado_id BIGINT NOT NULL REFERENCES grado(id),
    nombre VARCHAR(50) NOT NULL,
    turno VARCHAR(20) NOT NULL,
    capacidad INT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50),
    CONSTRAINT chk_seccion_turno CHECK (turno IN ('MANANA', 'TARDE')),
    CONSTRAINT chk_seccion_capacidad CHECK (capacidad > 0),
    CONSTRAINT uk_seccion_grado_nombre UNIQUE (grado_id, nombre),
    CONSTRAINT uk_seccion_id_grado UNIQUE (id, grado_id)
);

-- 11. TABLA: matricula
CREATE TABLE matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    persona_estudiante_id BIGINT NOT NULL REFERENCES persona(id),
    anio_escolar_id BIGINT NOT NULL REFERENCES anio_escolar(id),
    grado_id BIGINT NOT NULL REFERENCES grado(id),
    seccion_id BIGINT NOT NULL REFERENCES seccion(id),
    codigo_matricula VARCHAR(50) NOT NULL UNIQUE,
    fecha_matricula DATE NOT NULL DEFAULT CURRENT_DATE,
    estado VARCHAR(20) NOT NULL DEFAULT 'MATRICULADO',
    observaciones TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50),
    CONSTRAINT uk_matricula_estudiante_anio UNIQUE (persona_estudiante_id, anio_escolar_id),
    CONSTRAINT fk_matricula_seccion_grado FOREIGN KEY (seccion_id, grado_id) REFERENCES seccion(id, grado_id)
);

-- 12. TABLA: asistencia
CREATE TABLE asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL REFERENCES matricula(id),
    fecha DATE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    hora_ingreso TIME,
    hora_salida TIME,
    observacion VARCHAR(255),
    registrado_por BIGINT NOT NULL REFERENCES usuario(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50),
    CONSTRAINT uk_asistencia_matricula_fecha UNIQUE (matricula_id, fecha),
    CONSTRAINT chk_asistencia_estado CHECK (estado IN ('PRESENTE', 'TARDANZA', 'AUSENTE', 'JUSTIFICADO'))
);

-- 13. TABLA: justificacion
CREATE TABLE justificacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asistencia_id BIGINT NOT NULL REFERENCES asistencia(id),
    motivo VARCHAR(100) NOT NULL,
    descripcion TEXT,
    fecha_solicitud DATE NOT NULL DEFAULT CURRENT_DATE,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    observacion_revision VARCHAR(255),
    revisado_por BIGINT REFERENCES usuario(id),
    fecha_revision TIMESTAMP,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50),
    CONSTRAINT chk_justificacion_estado CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA'))
);

-- 14. TABLA: estudiante_apoderado
CREATE TABLE estudiante_apoderado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL REFERENCES persona(id),
    apoderado_id BIGINT NOT NULL REFERENCES persona(id),
    parentesco VARCHAR(20) NOT NULL,
    es_principal BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50),
    CONSTRAINT chk_estudiante_apoderado_distintos CHECK (estudiante_id <> apoderado_id),
    CONSTRAINT chk_estudiante_apoderado_parentesco CHECK (parentesco IN ('PADRE', 'MADRE', 'ABUELO', 'ABUELA', 'HERMANO', 'HERMANA', 'TIO', 'TIA', 'TUTOR', 'OTRO'))
);

-- 15. TABLA: horario_asistencia
CREATE TABLE horario_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_escolar_id BIGINT NOT NULL REFERENCES anio_escolar(id),
    turno VARCHAR(20) NOT NULL,
    grado_id BIGINT REFERENCES grado(id),
    seccion_id BIGINT REFERENCES seccion(id),
    hora_entrada TIME NOT NULL,
    minutos_tolerancia INT NOT NULL DEFAULT 0,
    hora_salida TIME NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50),
    CONSTRAINT chk_horario_turno CHECK (turno IN ('MANANA', 'TARDE')),
    CONSTRAINT chk_horario_tolerancia CHECK (minutos_tolerancia >= 0),
    CONSTRAINT chk_horario_horas CHECK (hora_salida > hora_entrada),
    CONSTRAINT chk_horario_fechas CHECK (fecha_fin >= fecha_inicio)
);

-- 16. TABLA: calendario_escolar
CREATE TABLE calendario_escolar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_escolar_id BIGINT NOT NULL REFERENCES anio_escolar(id),
    fecha DATE NOT NULL,
    tipo_dia VARCHAR(30) NOT NULL,
    descripcion VARCHAR(200),
    es_lectivo BOOLEAN NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50),
    CONSTRAINT chk_calendario_tipo_dia CHECK (tipo_dia IN ('FERIADO', 'NO_LABORABLE', 'SUSPENSION', 'ACTIVIDAD_INSTITUCIONAL', 'LECTIVO_EXTRAORDINARIO'))
);

-- 17. TABLA: configuracion_alerta_asistencia
CREATE TABLE configuracion_alerta_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(30) NOT NULL UNIQUE,
    umbral INT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50),
    CONSTRAINT chk_config_alerta_tipo CHECK (tipo IN ('AUSENCIAS_CONSECUTIVAS', 'AUSENCIAS_ACUMULADAS', 'TARDANZAS_ACUMULADAS')),
    CONSTRAINT chk_config_alerta_umbral CHECK (umbral > 0)
);

-- 18. TABLA: alerta_asistencia
CREATE TABLE alerta_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL REFERENCES matricula(id),
    tipo VARCHAR(30) NOT NULL,
    fecha_deteccion DATE NOT NULL,
    fecha_inicio_periodo DATE NOT NULL,
    fecha_fin_periodo DATE NOT NULL,
    cantidad INT NOT NULL,
    estado VARCHAR(20) NOT NULL,
    descripcion VARCHAR(255),
    revisado_por BIGINT REFERENCES usuario(id),
    fecha_revision TIMESTAMP,
    observacion_revision VARCHAR(500),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50),
    CONSTRAINT chk_alerta_tipo CHECK (tipo IN ('AUSENCIAS_CONSECUTIVAS', 'AUSENCIAS_ACUMULADAS', 'TARDANZAS_ACUMULADAS')),
    CONSTRAINT chk_alerta_estado CHECK (estado IN ('PENDIENTE', 'EN_REVISION', 'RESUELTA')),
    CONSTRAINT chk_alerta_cantidad CHECK (cantidad > 0)
);

-- 19. TABLA: notificacion
CREATE TABLE notificacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    tipo VARCHAR(30) NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    mensaje VARCHAR(500) NOT NULL,
    referencia_tipo VARCHAR(50),
    referencia_id BIGINT,
    url_destino VARCHAR(255),
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_lectura TIMESTAMP,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    updated_by VARCHAR(50),
    CONSTRAINT chk_notificacion_tipo CHECK (tipo IN ('ALERTA_ASISTENCIA', 'JUSTIFICACION_CREADA', 'JUSTIFICACION_APROBADA', 'JUSTIFICACION_RECHAZADA', 'SISTEMA'))
);

-- 20. TABLA: auditoria_evento (Auditoría funcional y trazabilidad inmutable)
CREATE TABLE auditoria_evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_id BIGINT REFERENCES usuario(id),
    username VARCHAR(100),
    accion VARCHAR(50) NOT NULL,
    modulo VARCHAR(50) NOT NULL,
    entidad_tipo VARCHAR(50),
    entidad_id BIGINT,
    resultado VARCHAR(20) NOT NULL,
    descripcion VARCHAR(500),
    direccion_ip VARCHAR(50),
    detalles TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

